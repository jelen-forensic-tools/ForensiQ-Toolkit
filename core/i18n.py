def t(key: str) -> str:
    """Return translated string for current language. Falls back to key if missing."""
    return TRANSLATIONS.get(_LANG, TRANSLATIONS["en"]).get(key, key)


def set_lang(lang: str) -> None:
    global _LANG
    if lang in TRANSLATIONS:
        _LANG = lang


def get_lang() -> str:
    return _LANG


def has(key: str) -> bool:
    """True if the key exists in the current (or fallback) language."""
    return key in TRANSLATIONS.get(_LANG, {}) or key in TRANSLATIONS["cs"]


def field_label(key: str) -> str:
    """Human-readable label for a data field/column key (uses kl.* translations)."""
    k = f"kl.{key}"
    if has(k):
        return t(k)
    return str(key).replace("_", " ").capitalize()


def retranslate(text: str, from_lang: str, to_lang: str):
    """
    If `text` is exactly a translation of some key in `from_lang`, return the
    `to_lang` translation of the same key; otherwise return None.
    Used to re-label static widgets after a language switch.
    """
    rev = _reverse_index(from_lang)
    key = rev.get(text)
    if key is None:
        return None
    return TRANSLATIONS.get(to_lang, {}).get(key)


_REV_CACHE: dict = {}


def _reverse_index(lang: str) -> dict:
    if lang not in _REV_CACHE:
        rev: dict = {}
        for k, v in TRANSLATIONS.get(lang, {}).items():
            if isinstance(v, str) and v and v not in rev:
                rev[v] = k
        _REV_CACHE[lang] = rev
    return _REV_CACHE[lang]
